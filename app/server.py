def csp_for(page):
    """The page's own inline scripts are allowed by their exact SHA-256 and nothing else is (no 'unsafe-inline'): a script
    injected through any text Kivy shows can't run (review F-08, 2026-10-25). Hashed after templating; the same page
    reuses its last header (W-05)."""
    if page is not None and page == _CSPC['page']:
        return _CSPC['csp']
    out = _csp_build(page)
    _CSPC.update(page=page, csp=out)
    return out


# The CSP header with a sha256 for each inline <script> of this page (index.html is built by tools/build_page.py).
def _csp_build(page):
    try:
        txt = page.decode() if isinstance(page, bytes) else str(page)
        hs = ["'sha256-%s'" % base64.b64encode(hashlib.sha256(b.encode()).digest()).decode()
              for b in re.findall(r'<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>', txt, re.S)]
    except Exception:
        hs = []
    return CSP.replace('{HASHES}', ''.join(h + ' ' for h in hs))


# The money gate (architecture programme change 3, 2026-11-14: it ran hidden inside Handler._send): every transaction a
# build route returns passes here on its way out — Kivy's fee added to the guard, the plan's steps and rules version, the
# plan saved (check 2 compares against it), the allowlist (pkg_watch) and the call rules (call_watch). Fails CLOSED.
def finish_build(path, req, code, body):
    """(code, body) for a build route's answer: unchanged unless it carries a transaction, which is checked and completed
    here or refused (422) / failed closed (500). Handler._send calls it for every POST to a TX_BUILD route."""
    if code == 200 and path in TX_BUILD:
        try:
            o = json.loads(body)
            if isinstance(o, dict) and (o.get('tx') or o.get('tx_kind')) and not o.get('guard'):
                raise ValueError('a transaction without a guard')   # every build carries one; without it nothing below would run
            fee = kivy_fee()
            if fee and len(intent_actions(path, req, o if isinstance(o, dict) else {})) < 2:
                fee = None                           # only multi-step transactions (PTBs with 2+ actions) pay Kivy's fee (2026-10-22)
            if path in ('/api/tx/check-send', '/api/tx/sendmany'):
                fee = None                           # sends are always free, even several in one (2026-10-23)
            if isinstance(o, dict) and o.get('guard') and fee and not o.get('gasless'):
                g = o['guard']                       # Kivy's flat fee: the browser adds it; this approves exactly it, to exactly us
                st = '0x2::sui::SUI'
                g['out'] = dict(g.get('out') or {}); g['out'][st] = str(int(g['out'].get(st) or 0) + int(fee['mist']))
                pays = g.get('pay') or []
                pays = pays if isinstance(pays, list) else [pays]
                g['pay'] = pays + [{'address': fee['address'], 'coin_type': st, 'amount': fee['mist'], 'max': fee['mist']}]   # exactly the fee (S2)
                g['fee'] = {'address': fee['address'], 'mist': fee['mist']}
                body = json.dumps(o)
            if isinstance(o, dict) and o.get('guard'):
                p0 = path
                steps = plan_steps(p0, req, o)   # the call rules: what this plan's transaction may call (2026-11-13)
                o['guard']['steps'] = sorted(steps)
                o['guard']['swap'] = 'swap' in steps          # check 1 trusts a route-only coin only in a real swap (zero-day review C)
                o['guard']['perps'] = 'perps' in steps        # check 1 refuses perps calls unless this is a perps plan (review K-4)
                o['guard']['policy'] = policy_version()       # the rules that judged it; the page refuses another version (change 5)
                PLAN.shadow(p0, req, steps, intent_actions(p0, req, o))   # plan-first shadow (change 9): counts only
                o['intent_id'] = remember_intent(path, req, o)
                o['guard']['iid'] = o['intent_id']       # the page reports each check against this plan (stats pipeline)
                o['guard']['vol'] = {k: str(v) for k, v in (_INTENTS.get(o['intent_id'], {}).get('vol') or {}).items()}
                tx_for_check = o.get('tx') or None       # '' or {} is no transaction, never an unread one (S3, 2026-11-15)
                if not tx_for_check and o.get('tx_kind'):  # a plain swap comes as a BCS kind: the builder lists its calls (S-02)
                    try:
                        kc = lend_post('/kind-calls', {'kind': o['tx_kind']}, timeout=20)
                        # every non-call command by its kind: pkg_watch refuses any kind it does not know, not only Publish / Upgrade (S3)
                        tx_for_check = {'commands': [{'MoveCall': c} for c in kc['calls']] + [{str(o): {}} for o in kc.get('others') or []]} \
                            if kc.get('ok') and kc.get('calls') else None   # non-call commands too (audit nv #2)   # a swap with no calls = not read
                    except Exception:
                        tx_for_check = None
                    if tx_for_check is None:             # can't read it: refused, never waved through unchecked
                        print('kivy refused build: could not list the calls of %s' % path, flush=True)
                unreadable = bool(o.get('tx_kind')) and not o.get('tx') and tx_for_check is None
                bad = ['unreadable transaction'] if unreadable else pkg_watch(path, tx_for_check)   # a send has no tx here: the page builds it
                rule = [] if bad else call_watch(p0, tx_for_check, steps)   # a function this plan's steps don't need (2026-11-13)
                body = json.dumps(o)
                if bad:                              # a program Kivy hasn't verified: refused here, not just in the browser (F-04)
                    print('kivy refused build: unlisted %s' % ', '.join(bad), flush=True)
                    code, body = 422, json.dumps({'error': "This transaction would call a program Kivy hasn't verified (%s), so I didn't prepare it." % bad[0]})
                elif rule:
                    print('kivy refused build: call rule %s steps=%s %s' % (p0, ','.join(sorted(steps)) or '-', ', '.join(rule[:4])), flush=True)
                    code, body = 422, json.dumps({'error': "This transaction would call something its plan doesn't need (%s), so I didn't prepare it." % rule[0].split(' (')[0]})
        except Exception as exc:                     # fail CLOSED (OWASP A10-1, 2026-10-29): a build whose checks broke is never handed out
            print('kivy refused build: post-check failed %s (%s)' % (path, type(exc).__name__), flush=True)
            code, body = 500, json.dumps({'error': "Kivy couldn't check this transaction, so nothing was prepared. Try again in a minute."})
    return code, body


