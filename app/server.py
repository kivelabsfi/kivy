def paused():
    """The reason while Kivy is paused (never empty), else ''. A PAUSED that exists but can't be read counts as paused."""
    try:
        with open(PAUSE_FILE, encoding='utf-8', errors='replace') as f:
            why = f.readline(400)
    except FileNotFoundError:
        return ''
    except OSError:
        return 'maintenance'
    why = re.sub(r'\s+', ' ', re.sub(r'[\x00-\x1f\x7f<>"\\]+', ' ', why)).strip()[:120].strip().rstrip('.')
    return why or 'maintenance'


